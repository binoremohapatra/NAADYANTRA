#!/usr/bin/env python3
"""
train_hazard_fusion.py - tabular multi-sensor hazard model -> zero-dependency C header.

Trains a small RandomForest (soft voting) on hazard_telemetry.csv and exports it as
constant node tables + a branch-only traversal function (no heap, no recursion, no libs).
Custom exporter is used instead of emlearn so the header has no external dependency.

Feature order (MUST match firmware):
  0 distance_mm  1 distance_velocity  2 temp_object  3 temp_ambient
  4 delta_temp   5 uv_index           6 gas_ppm_slope
States: 0 Normal, 1 Safe Arc, 2 Proximity Breach, 3 Gas Buildup, 4 Workpiece Overheat

Usage: python train_hazard_fusion.py --csv hazard_telemetry.csv --out firmware/main/hazard_model.h
"""
import argparse
import os

import numpy as np
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import confusion_matrix
from sklearn.model_selection import train_test_split
from sklearn.tree import DecisionTreeClassifier

FEATURES = ["distance_mm", "distance_velocity", "temp_object", "temp_ambient",
            "delta_temp", "uv_index", "gas_ppm_slope"]
STATES = ["Normal", "Safe Arc", "Proximity Breach", "Gas Buildup", "Workpiece Overheat"]


def load(path):
    d = np.genfromtxt(path, delimiter=",", names=True)
    X = np.column_stack([d[f] for f in FEATURES]).astype(np.float32)
    return X, d["hazard_state"].astype(np.int64)


def flatten_forest(trees, n_classes):
    """-> nodes (feature, threshold, left, right) , leaf probs (uint8 x n_classes), roots."""
    feat, thr, left, right, leaf_prob, roots = [], [], [], [], [], []
    for est in trees:
        t = est.tree_
        base = len(feat)
        roots.append(base)
        # sklearn node ids are contiguous 0..n-1 -> offset by base
        for n in range(t.node_count):
            if t.children_left[n] == -1:                       # leaf
                v = t.value[n][0]
                p = v / v.sum()
                feat.append(-1)
                thr.append(0.0)
                left.append(len(leaf_prob))                    # leaf index
                right.append(-1)
                leaf_prob.append(np.round(p * 255).astype(np.uint8))
            else:
                feat.append(int(t.feature[n]))
                thr.append(float(np.float32(t.threshold[n])))
                left.append(base + int(t.children_left[n]))
                right.append(base + int(t.children_right[n]))
    return feat, thr, left, right, np.array(leaf_prob, dtype=np.uint8), roots


def predict_exported(x, feat, thr, left, right, leaf_prob, roots, n_classes):
    """Python replica of the C traversal (float32 compares, uint8 soft votes)."""
    acc = np.zeros(n_classes, dtype=np.int32)
    for r in roots:
        n = r
        while feat[n] >= 0:
            n = left[n] if np.float32(x[feat[n]]) <= np.float32(thr[n]) else right[n]
        acc += leaf_prob[left[n]]
    best = 0
    for c in range(n_classes):          # ties -> higher class index (more severe)
        if acc[c] >= acc[best]:
            best = c
    return best


def emit_header(path, feat, thr, left, right, leaf_prob, roots, n_classes, acc):
    n_nodes = len(feat)
    L = []
    L.append("// AUTO-GENERATED by train_hazard_fusion.py - do not edit.")
    L.append("// RandomForest hazard classifier: static tables, no heap, no recursion.")
    L.append(f"// Hold-out accuracy on synthetic telemetry: {acc*100:.2f}%")
    L.append("#pragma once")
    L.append("#include <stdint.h>")
    L.append("")
    L.append(f"#define HZ_FEATURE_COUNT {len(FEATURES)}")
    L.append(f"#define HZ_NUM_CLASSES   {n_classes}")
    L.append(f"#define HZ_NUM_TREES     {len(roots)}")
    L.append(f"#define HZ_NUM_NODES     {n_nodes}")
    L.append(f"#define HZ_NUM_LEAVES    {len(leaf_prob)}")
    L.append("// feature index map: " + ", ".join(f"{i}={n}" for i, n in enumerate(FEATURES)))
    L.append("")
    L.append(f"static const int8_t  HZ_NODE_FEATURE[HZ_NUM_NODES] = {{{', '.join(map(str, feat))}}};")
    L.append("static const float   HZ_NODE_THRESH[HZ_NUM_NODES] = {")
    for i in range(0, n_nodes, 6):
        L.append("  " + ", ".join(f"{v:.9e}f" for v in thr[i:i + 6]) + ",")
    L.append("};")
    L.append("// internal node: left/right child index. leaf node: HZ_NODE_LEFT = leaf index")
    L.append(f"static const int16_t HZ_NODE_LEFT[HZ_NUM_NODES]  = {{{', '.join(map(str, left))}}};")
    L.append(f"static const int16_t HZ_NODE_RIGHT[HZ_NUM_NODES] = {{{', '.join(map(str, right))}}};")
    L.append(f"static const int16_t HZ_TREE_ROOT[HZ_NUM_TREES]  = {{{', '.join(map(str, roots))}}};")
    L.append("static const uint8_t HZ_LEAF_PROB[HZ_NUM_LEAVES][HZ_NUM_CLASSES] = {")
    for p in leaf_prob:
        L.append("  {" + ", ".join(map(str, p)) + "},")
    L.append("};")
    L.append("")
    L.append("// x[] in the feature order above. Returns hazard state 0..4; *conf_pct = vote share 0..100.")
    L.append("static inline int hazard_predict(const float *x, uint8_t *conf_pct)")
    L.append("{")
    L.append("    uint32_t acc[HZ_NUM_CLASSES] = {0};")
    L.append("    for (int t = 0; t < HZ_NUM_TREES; ++t) {")
    L.append("        int n = HZ_TREE_ROOT[t];")
    L.append("        while (HZ_NODE_FEATURE[n] >= 0) {")
    L.append("            n = (x[HZ_NODE_FEATURE[n]] <= HZ_NODE_THRESH[n]) ? HZ_NODE_LEFT[n] : HZ_NODE_RIGHT[n];")
    L.append("        }")
    L.append("        const uint8_t *p = HZ_LEAF_PROB[HZ_NODE_LEFT[n]];")
    L.append("        for (int c = 0; c < HZ_NUM_CLASSES; ++c) acc[c] += p[c];")
    L.append("    }")
    L.append("    int best = 0; uint32_t total = 0;")
    L.append("    for (int c = 0; c < HZ_NUM_CLASSES; ++c) {")
    L.append("        total += acc[c];")
    L.append("        if (acc[c] >= acc[best]) best = c;      /* ties -> more severe class */")
    L.append("    }")
    L.append("    if (conf_pct) *conf_pct = total ? (uint8_t)((acc[best] * 100u) / total) : 0;")
    L.append("    return best;")
    L.append("}")
    with open(path, "w") as f:
        f.write("\n".join(L) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv", default="hazard_telemetry.csv")
    ap.add_argument("--out", default="firmware/main/hazard_model.h")
    ap.add_argument("--trees", type=int, default=8)
    ap.add_argument("--depth", type=int, default=6)
    ap.add_argument("--seed", type=int, default=11)
    args = ap.parse_args()

    X, y = load(args.csv)
    Xtr, Xte, ytr, yte = train_test_split(X, y, test_size=0.2, stratify=y, random_state=args.seed)

    dt = DecisionTreeClassifier(max_depth=args.depth, min_samples_leaf=5, random_state=args.seed).fit(Xtr, ytr)
    rf = RandomForestClassifier(n_estimators=args.trees, max_depth=args.depth, min_samples_leaf=5,
                                random_state=args.seed, n_jobs=-1).fit(Xtr, ytr)
    print(f"DecisionTree  acc: {dt.score(Xte, yte)*100:.2f}%  nodes: {dt.tree_.node_count}")
    print(f"RandomForest  acc: {rf.score(Xte, yte)*100:.2f}%  nodes: {sum(e.tree_.node_count for e in rf.estimators_)}")
    print("confusion (rows=true):", STATES)
    print(confusion_matrix(yte, rf.predict(Xte)))
    print("feature importance:", {n: round(float(v), 3) for n, v in zip(FEATURES, rf.feature_importances_)})

    n_classes = len(STATES)
    feat, thr, left, right, leaf_prob, roots = flatten_forest(rf.estimators_, n_classes)
    exp_pred = np.array([predict_exported(x, feat, thr, left, right, leaf_prob, roots, n_classes) for x in Xte])
    acc = float(np.mean(exp_pred == yte))
    agree = float(np.mean(exp_pred == rf.predict(Xte)))
    print(f"exported-model acc: {acc*100:.2f}%   agreement with sklearn: {agree*100:.2f}%")

    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    emit_header(args.out, feat, thr, left, right, leaf_prob, roots, n_classes, acc)
    flash = len(feat) * (1 + 4 + 2 + 2) + len(leaf_prob) * n_classes + len(roots) * 2
    print(f"[export] {args.out}: {len(feat)} nodes, {len(leaf_prob)} leaves, ~{flash} B flash")

    # self-test vectors (features + expected class) so the C traversal can be checked on a host
    tv = os.path.join(os.path.dirname(os.path.abspath(args.csv)), "hazard_selftest.csv")
    np.savetxt(tv, np.column_stack([Xte[:200], exp_pred[:200]]), delimiter=",", fmt="%.6g")


if __name__ == "__main__":
    main()
