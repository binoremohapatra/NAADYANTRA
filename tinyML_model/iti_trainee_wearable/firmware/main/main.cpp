/*
 * ITI Trainee Diagnostic Wearable - ESP32-WROOM-32E firmware (ESP-IDF v5.1 - v5.3)
 *
 *  Core 1 (high prio)  : ADC1 DMA stream (piezo @16 kHz + MQ-2 + GUVA) -> 500 ms ring ->
 *                        32x32 log-Mel (fixed tables) -> INT8 TFLite-Micro (MicroMutableOpResolver<5>)
 *                        -> acoustic queue
 *  Core 0 (normal prio): 20 Hz sensor poll (MLX90614, VL53L0X over I2C; MQ-2/UV from the ADC1 stream),
 *                        C hazard-fusion forest, NSQF trainee assessment, OLED, LEDs, buzzer, BLE GATT.
 *
 * ADC1 note: on the ESP32 the DMA (digital) controller and one-shot reads cannot share ADC1.
 * Piezo, MQ-2 and GUVA are all ADC1 pins, so all three are sampled in ONE continuous DMA pattern
 * (3 x 16 kHz). Core 1 demultiplexes by channel tag and hands Core 0 oversampled MQ-2/UV averages,
 * which Core 0 consumes at 20 Hz.
 */
