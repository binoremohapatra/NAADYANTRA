static void adc_dma_init()
{
    adc_continuous_handle_cfg_t hc = {};
    hc.max_store_buf_size = 16384;      // ~170 ms of slack at 96 kB/s
    hc.conv_frame_size    = 960;
    ESP_ERROR_CHECK(adc_continuous_new_handle(&hc, &g_adc));

    static adc_digi_pattern_config_t pat[N_ADC_CH];
    const uint8_t chs[N_ADC_CH] = { CH_PIEZO, CH_MQ2, CH_UV };
    for (int i = 0; i < N_ADC_CH; ++i) {
        pat[i].atten = ADC_ATTEN_DB_12;
        pat[i].channel = chs[i];
        pat[i].unit = ADC_UNIT_1;
        pat[i].bit_width = ADC_BITWIDTH_12;
    }
    adc_continuous_config_t cfg = {};
    cfg.pattern_num = N_ADC_CH;
    cfg.adc_pattern = pat;
    cfg.sample_freq_hz = ADC_CONV_RATE_HZ;
    cfg.conv_mode = ADC_CONV_SINGLE_UNIT_1;
    cfg.format = ADC_DIGI_OUTPUT_FORMAT_TYPE1;
    ESP_ERROR_CHECK(adc_continuous_config(g_adc, &cfg));
    ESP_ERROR_CHECK(adc_continuous_start(g_adc));
}

// in-place radix-2 DIT FFT, N = MEL_N_FFT, twiddles from mel_tables.h
static void fft512(float *re, float *im)
{
    const int n = MEL_N_FFT;
    for (int i = 1, j = 0; i < n; ++i) {
        int bit = n >> 1;
        for (; j & bit; bit >>= 1) j ^= bit;
        j ^= bit;
        if (i < j) { float t = re[i]; re[i] = re[j]; re[j] = t; t = im[i]; im[i] = im[j]; im[j] = t; }
    }
    for (int len = 2; len <= n; len <<= 1) {
        const int half = len >> 1, step = n / len;
        for (int i = 0; i < n; i += len) {
            for (int k = 0; k < half; ++k) {
                const float wr = MEL_TW_COS[k * step], wi = MEL_TW_SIN[k * step];
                const int a = i + k, b = a + half;
                const float vr = re[b] * wr - im[b] * wi;
                const float vi = re[b] * wi + im[b] * wr;
                re[b] = re[a] - vr; im[b] = im[a] - vi;
                re[a] += vr;        im[a] += vi;
            }
        }
    }
}

// Builds the (32,32,1) INT8 tensor from the last 500 ms in the ring (oldest sample at g_wr).
static void extract_logmel(int8_t *dst, float in_scale, int in_zp)
{
    double sum = 0.0;
    for (int i = 0; i < MEL_WIN_SAMPLES; ++i) sum += g_ring[i];
    const float mean = (float)(sum / MEL_WIN_SAMPLES);
    double sq = 0.0;
    for (int i = 0; i < MEL_WIN_SAMPLES; ++i) { const float d = (float)g_ring[i] - mean; sq += (double)d * d; }
    const float rms = sqrtf((float)(sq / MEL_WIN_SAMPLES));
    float gain = MEL_NORM_RMS / (rms + 1e-9f);
    if (gain > 1000.0f) gain = 1000.0f;                       // identical to train_quantize.rms_normalise
    const float inv_range = 1.0f / (MEL_DB_MAX - MEL_DB_MIN);
    const float inv_scale = 1.0f / in_scale;

    float power[MEL_N_FFT / 2 + 1];
    for (int t = 0; t < MEL_N_FRAMES; ++t) {
        uint32_t base = g_wr + (uint32_t)t * MEL_HOP;
        for (int n = 0; n < MEL_N_FFT; ++n) {
            uint32_t idx = base + n;
            if (idx >= MEL_WIN_SAMPLES) idx -= MEL_WIN_SAMPLES;
            g_re[n] = ((float)g_ring[idx] - mean) * gain * MEL_HANN[n];
            g_im[n] = 0.0f;
        }
        fft512(g_re, g_im);
        for (int k = 0; k <= MEL_N_FFT / 2; ++k) power[k] = g_re[k] * g_re[k] + g_im[k] * g_im[k];
        for (int m = 0; m < MEL_N_MELS; ++m) {
            const float *w = &MEL_FB_W[MEL_FB_OFFSET[m]];
            const float *p = &power[MEL_FB_START[m]];
            float acc = 0.0f;
            for (int j = 0; j < MEL_FB_LEN[m]; ++j) acc += w[j] * p[j];
            const float db = 10.0f * log10f(acc + MEL_DB_EPS);
            float f = (db - MEL_DB_MIN) * inv_range;
            f = f < 0.0f ? 0.0f : (f > 1.0f ? 1.0f : f);
            int q = (int)lroundf(f * inv_scale) + in_zp;
            q = q < -128 ? -128 : (q > 127 ? 127 : q);
            dst[t * MEL_N_MELS + m] = (int8_t)q;
        }
    }
}

static void core1_audio_task(void *)
{
    adc_dma_init();

    // ---- TFLite Micro
    const tflite::Model *model = tflite::GetModel(g_model_data);
    if (model->version() != TFLITE_SCHEMA_VERSION) {
        ESP_LOGE(TAG, "model schema %lu != %d", (unsigned long)model->version(), TFLITE_SCHEMA_VERSION);
        vTaskDelete(NULL);
    }
    static tflite::MicroMutableOpResolver<5> resolver;
    resolver.AddConv2D();
    resolver.AddDepthwiseConv2D();
    resolver.AddFullyConnected();
    resolver.AddMean();
    resolver.AddSoftmax();
    static tflite::MicroInterpreter interp(model, resolver, g_arena, sizeof(g_arena));
    if (interp.AllocateTensors() != kTfLiteOk) {
        ESP_LOGE(TAG, "AllocateTensors failed (arena %d B too small?)", TENSOR_ARENA_SZ);
        vTaskDelete(NULL);
    }
    TfLiteTensor *in = interp.input(0), *out = interp.output(0);
    if (in->type != kTfLiteInt8 || in->bytes != MEL_N_FRAMES * MEL_N_MELS ||
        out->type != kTfLiteInt8 || out->dims->data[out->dims->size - 1] != MODEL_NUM_CLASSES) {
        ESP_LOGE(TAG, "unexpected model I/O (type/shape)");
        vTaskDelete(NULL);
    }
    const float in_scale = in->params.scale, out_scale = out->params.scale;
    const int in_zp = in->params.zero_point, out_zp = out->params.zero_point;
    ESP_LOGI(TAG, "TFLM ready: arena used %u / %d B, model %u B",
             (unsigned)interp.arena_used_bytes(), TENSOR_ARENA_SZ, (unsigned)g_model_data_len);
    g_ac_ok = true;

    static uint8_t rb[960];
    uint32_t since = 0;
    bool primed = false;
    uint32_t rate_t0 = now_ms(), rate_cnt = 0;
    bool rate_checked = false;

    for (;;) {
        uint32_t n = 0;
        esp_err_t r = adc_continuous_read(g_adc, rb, sizeof(rb), &n, 20);
        if (r != ESP_OK) { if (r != ESP_ERR_TIMEOUT) vTaskDelay(1); continue; }

        uint32_t sum[2] = {0, 0}, cnt[2] = {0, 0};
        for (uint32_t i = 0; i + SOC_ADC_DIGI_RESULT_BYTES <= n; i += SOC_ADC_DIGI_RESULT_BYTES) {
            const adc_digi_output_data_t *p = (const adc_digi_output_data_t *)&rb[i];
            const uint32_t ch = ADC_CH(p), d = ADC_DATA(p);
            if (ch == CH_PIEZO) {
                g_ring[g_wr] = (uint16_t)d;
                if (++g_wr >= MEL_WIN_SAMPLES) { g_wr = 0; primed = true; }
                ++since; ++rate_cnt;
            } else if (ch == CH_MQ2) { sum[0] += d; ++cnt[0]; }
            else if (ch == CH_UV)    { sum[1] += d; ++cnt[1]; }
        }
        portENTER_CRITICAL(&g_slow_mux);
        for (int k = 0; k < 2; ++k) { g_slow.sum[k] += sum[k]; g_slow.cnt[k] += cnt[k]; }
        portEXIT_CRITICAL(&g_slow_mux);

        if (!rate_checked && now_ms() - rate_t0 >= 2000) {       // sanity-check the real sample rate
            const float hz = rate_cnt * 1000.0f / (float)(now_ms() - rate_t0);
            ESP_LOGI(TAG, "piezo channel rate: %.0f Hz (expected %d)", hz, AUDIO_FS);
            if (fabsf(hz - AUDIO_FS) > 0.05f * AUDIO_FS)
                ESP_LOGE(TAG, "ADC rate off by >5%%: adjust ADC_CONV_RATE_HZ (features assume %d Hz)", AUDIO_FS);
            rate_checked = true;
        }

        if (primed && since >= INFER_HOP) {
            since -= INFER_HOP;
            extract_logmel(in->data.int8, in_scale, in_zp);
            if (interp.Invoke() != kTfLiteOk) { ESP_LOGE(TAG, "Invoke failed"); continue; }
            int best = 0; float pbest = -1.0f;
            for (int c = 0; c < MODEL_NUM_CLASSES; ++c) {
                const float p = ((int)out->data.int8[c] - out_zp) * out_scale;
                if (p > pbest) { pbest = p; best = c; }
            }
            AcousticMsg m;
            m.cls = (uint8_t)best;
            m.conf_pct = (uint8_t)(pbest < 0 ? 0 : (pbest > 1 ? 100 : pbest * 100.0f + 0.5f));
            m.ts_ms = now_ms();
            xQueueSend(g_ac_q, &m, 0);                                 // drop if Core 0 is behind
        }
    }
}

