static BleAssessPkt g_assess_pkt;
static struct ble_gatt_chr_def g_chrs[4];
static struct ble_gatt_svc_def g_svcs[2];

static int alert_access(uint16_t, uint16_t, struct ble_gatt_access_ctxt *ctxt, void *)
{
    return os_mbuf_append(ctxt->om, &g_alert_pkt, sizeof(g_alert_pkt)) == 0 ? 0 : BLE_ATT_ERR_INSUFFICIENT_RES;
}
static int assess_access(uint16_t, uint16_t, struct ble_gatt_access_ctxt *ctxt, void *)
{
    return os_mbuf_append(ctxt->om, &g_assess_pkt, sizeof(g_assess_pkt)) == 0 ? 0 : BLE_ATT_ERR_INSUFFICIENT_RES;
}
static int ctrl_access(uint16_t, uint16_t, struct ble_gatt_access_ctxt *ctxt, void *)
{
    if (ctxt->op != BLE_GATT_ACCESS_OP_WRITE_CHR) return BLE_ATT_ERR_UNLIKELY;
    uint8_t b[4]; uint16_t got = 0;
    const uint16_t len = OS_MBUF_PKTLEN(ctxt->om);
    if (len < 1 || len > sizeof(b)) return BLE_ATT_ERR_INVALID_ATTR_VALUE_LEN;
    if (ble_hs_mbuf_to_flat(ctxt->om, b, sizeof(b), &got) != 0) return BLE_ATT_ERR_UNLIKELY;
    xQueueSend(g_ctrl_q, &b[0], 0);
    return 0;
}

static void gatt_build()
{
    memset(g_chrs, 0, sizeof(g_chrs));
    memset(g_svcs, 0, sizeof(g_svcs));
    g_chrs[0].uuid = &UUID_ALERT.u;  g_chrs[0].access_cb = alert_access;
    g_chrs[0].flags = BLE_GATT_CHR_F_READ | BLE_GATT_CHR_F_NOTIFY; g_chrs[0].val_handle = &g_h_alert;
    g_chrs[1].uuid = &UUID_ASSESS.u; g_chrs[1].access_cb = assess_access;
    g_chrs[1].flags = BLE_GATT_CHR_F_READ | BLE_GATT_CHR_F_NOTIFY; g_chrs[1].val_handle = &g_h_assess;
    g_chrs[2].uuid = &UUID_CTRL.u;   g_chrs[2].access_cb = ctrl_access;
    g_chrs[2].flags = BLE_GATT_CHR_F_WRITE;
    // g_chrs[3] stays zeroed = terminator
    g_svcs[0].type = BLE_GATT_SVC_TYPE_PRIMARY;
    g_svcs[0].uuid = &UUID_SVC.u;
    g_svcs[0].characteristics = g_chrs;
}

static void ble_advertise();
static int gap_event(struct ble_gap_event *ev, void *)
{
    switch (ev->type) {
    case BLE_GAP_EVENT_CONNECT:
        if (ev->connect.status != 0) ble_advertise();
        break;
    case BLE_GAP_EVENT_DISCONNECT:
    case BLE_GAP_EVENT_ADV_COMPLETE:
        ble_advertise();
        break;
    default: break;
    }
    return 0;
}

static void ble_advertise()
{
    struct ble_hs_adv_fields f;
    memset(&f, 0, sizeof(f));
    f.flags = BLE_HS_ADV_F_DISC_GEN | BLE_HS_ADV_F_BREDR_UNSUP;
    const char *name = ble_svc_gap_device_name();
    f.name = (const uint8_t *)name; f.name_len = (uint8_t)strlen(name); f.name_is_complete = 1;
    ble_gap_adv_set_fields(&f);
    struct ble_hs_adv_fields rsp;
    memset(&rsp, 0, sizeof(rsp));
    rsp.uuids128 = &UUID_SVC; rsp.num_uuids128 = 1; rsp.uuids128_is_complete = 1;
    ble_gap_adv_rsp_set_fields(&rsp);
    struct ble_gap_adv_params ap;
    memset(&ap, 0, sizeof(ap));
    ap.conn_mode = BLE_GAP_CONN_MODE_UND;
    ap.disc_mode = BLE_GAP_DISC_MODE_GEN;
    const int rc = ble_gap_adv_start(g_own_addr, NULL, BLE_HS_FOREVER, &ap, gap_event, NULL);
    if (rc != 0 && rc != BLE_HS_EALREADY) ESP_LOGE(TAG, "adv start rc=%d", rc);
}

static void ble_on_sync()
{
    ble_hs_util_ensure_addr(0);
    ble_hs_id_infer_auto(0, &g_own_addr);
    ble_advertise();
    g_ble_ready = true;
}
static void ble_on_reset(int reason) { g_ble_ready = false; ESP_LOGW(TAG, "BLE reset, reason %d", reason); }
static void ble_host_task(void *) { nimble_port_run(); nimble_port_freertos_deinit(); }

static void ble_init()
{
    gatt_build();
    ESP_ERROR_CHECK(nimble_port_init());
    ble_hs_cfg.reset_cb = ble_on_reset;
    ble_hs_cfg.sync_cb = ble_on_sync;
    ble_svc_gap_init();
    ble_svc_gatt_init();
    ESP_ERROR_CHECK(ble_gatts_count_cfg(g_svcs) == 0 ? ESP_OK : ESP_FAIL);
    ESP_ERROR_CHECK(ble_gatts_add_svcs(g_svcs) == 0 ? ESP_OK : ESP_FAIL);
    ble_svc_gap_device_name_set("ITI-Trainer");
    nimble_port_freertos_init(ble_host_task);
}

static void ble_publish(uint8_t level, bool force, uint32_t now)
{
    static BleAlertPkt last_alert;
    static uint32_t last_alert_ms = 0, last_assess_ms = 0;

    BleAlertPkt a;
    a.level = level; a.hazard = (uint8_t)g_hz_state;
    a.acoustic = g_have_ac ? g_last_ac.cls : 0; a.conf = g_have_ac ? g_last_ac.conf_pct : 0;
    a.dist_mm = (uint16_t)g_f.distance_mm;
    a.temp_obj_x10 = (int16_t)lroundf(g_f.temp_object * 10.0f);
    a.uv_x10 = (uint16_t)lroundf(g_f.uv_index * 10.0f);
    a.gas_slope_x10 = (int16_t)lroundf(g_f.gas_ppm_slope * 10.0f);
    const bool changed = a.level != last_alert.level || a.hazard != last_alert.hazard || a.acoustic != last_alert.acoustic;
    g_alert_pkt = a;
    if (g_ble_ready && (changed || force || now - last_alert_ms >= 1000)) {
        ble_gatts_chr_updated(g_h_alert);
        last_alert = a; last_alert_ms = now;
    }

    BleAssessPkt s;
    s.state = g_as.running ? 1 : (g_as.complete ? 2 : 0);
    s.score = g_as.complete ? g_as.score : compute_score();
    s.reaction_ms = !g_as.onset_marked ? 0xFFFF : (g_as.reaction_ms < 0 ? (g_as.running ? 0xFFFF : 0xFFFE)
                                                                          : (uint16_t)(g_as.reaction_ms > 65000 ? 65000 : g_as.reaction_ms));
    s.false_alarms = (uint8_t)(g_as.false_alarms > 255 ? 255 : g_as.false_alarms);
    bool v; const float sp = standoff_pct(&v);
    s.standoff_pct = v ? (uint8_t)(sp + 0.5f) : 255;
    s.arc_s = (uint16_t)(g_as.arc_ticks * SENSOR_PERIOD_MS / 1000);
    s.session_s = (uint16_t)(((g_as.running ? now : g_as.end_ms) - g_as.start_ms) / 1000);
    if (s.state == 0) s.session_s = 0;
    g_assess_pkt = s;
    if (g_ble_ready && (force || now - last_assess_ms >= 1000)) {
        ble_gatts_chr_updated(g_h_assess);
        last_assess_ms = now;
    }
}

// ============================================================================ UI: LEDs, buzzer, OLED
static const char *AC_NAMES[]  = { "NORMAL", "CLATTER", "MINOR LEAK", "MAJOR LEAK" };
static const char *HZ_NAMES[]  = { "NORMAL", "SAFE ARC", "PROXIMITY", "GAS BUILDUP", "OVERHEAT" };

static void set_leds(uint8_t level)
{
    gpio_set_level((gpio_num_t)PIN_LED_GREEN, level == LVL_NORMAL);
    gpio_set_level((gpio_num_t)PIN_LED_AMBER, level == LVL_WARNING);
    gpio_set_level((gpio_num_t)PIN_LED_RED,   level == LVL_CRITICAL);
}

static void drive_buzzer(uint8_t level, uint32_t tick)
{
    bool on = false;
    if (level == LVL_CRITICAL)      on = (tick % 6) < 3;        // 150 ms on / 150 ms off
    else if (level == LVL_WARNING)  on = (tick % 20) < 2;       // 100 ms beep every second
    gpio_set_level((gpio_num_t)PIN_BUZZER, on);
}

static void reaction_str(char *dst, size_t n)
{
    if (!g_as.onset_marked) snprintf(dst, n, "N/A");
    else if (g_as.reaction_ms < 0) snprintf(dst, n, g_as.running ? "WAITING" : "MISSED");
    else snprintf(dst, n, "%.1f S", g_as.reaction_ms / 1000.0f);
}

static void draw_ui(uint8_t level, uint32_t now)
{
    char b[40], rt[16];
    reaction_str(rt, sizeof(rt));
    bool v; const float sp = standoff_pct(&v);

    if (g_as.complete && !g_as.running) {
        oled_row(0, "SESSION COMPLETE", true);
        snprintf(b, sizeof(b), "REACTION: %s", rt);                     oled_row(1, b);
        snprintf(b, sizeof(b), "FALSE ALARMS: %u", g_as.false_alarms);   oled_row(2, b);
        if (v) snprintf(b, sizeof(b), "STANDOFF: %.0f %%", sp); else snprintf(b, sizeof(b), "STANDOFF: N/A");
        oled_row(3, b);
        snprintf(b, sizeof(b), "SCORE: %u/100", g_as.score);            oled_row(4, b);
        oled_row(5, g_as.score >= NSQF_PASS_SCORE ? "RESULT: COMPETENT" : "RESULT: NOT YET COMP.", true);
        snprintf(b, sizeof(b), "TIME: %us", (unsigned)((g_as.end_ms - g_as.start_ms) / 1000)); oled_row(6, b);
        oled_row(7, "BTN: NEW SESSION");
        return;
    }

    const uint32_t secs = g_as.running ? (now - g_as.start_ms) / 1000 : 0;
    snprintf(b, sizeof(b), "%s %02u:%02u %s", g_as.running ? "RUN " : "IDLE", (unsigned)(secs / 60), (unsigned)(secs % 60),
             g_ble_ready ? "BLE" : "");
    oled_row(0, b, true);
    if (!g_ac_ok) snprintf(b, sizeof(b), "AC: MODEL ERROR");
    else if (!g_have_ac) snprintf(b, sizeof(b), "AC: LISTENING...");
    else snprintf(b, sizeof(b), "AC:%s %u%%", AC_NAMES[g_last_ac.cls & 3], g_last_ac.conf_pct);
    oled_row(1, b);
    snprintf(b, sizeof(b), "HZ:%s", HZ_NAMES[g_hz_state % 5]);           oled_row(2, b);
    if (g_vl_ok) snprintf(b, sizeof(b), "D:%4dMM V:%+d", (int)g_f.distance_mm, (int)g_f.distance_velocity);
    else snprintf(b, sizeof(b), "D: NO TOF SENSOR");
    oled_row(3, b);
    if (g_mlx_ok) snprintf(b, sizeof(b), "OBJ:%dC AMB:%dC", (int)lroundf(g_f.temp_object), (int)lroundf(g_f.temp_ambient));
    else snprintf(b, sizeof(b), "T: NO IR SENSOR");
    oled_row(4, b);
    snprintf(b, sizeof(b), "UV:%.1f GAS:%+.1f/S", g_f.uv_index, g_f.gas_ppm_slope);   oled_row(5, b);
    snprintf(b, sizeof(b), "FA:%u RT:%s%s", g_as.false_alarms, rt, g_as.leak_sim ? " DRILL" : ""); oled_row(6, b);
    if (v || g_as.arc_ticks) snprintf(b, sizeof(b), "%s ARC:%.0f%%", level == LVL_CRITICAL ? "CRITICAL" : (level == LVL_WARNING ? "WARNING" : "SAFE"), sp);
    else snprintf(b, sizeof(b), "%s", level == LVL_CRITICAL ? "** CRITICAL **" : (level == LVL_WARNING ? "* WARNING *" : "SAFE"));
    oled_row(7, b, level != LVL_NORMAL);
}

// ============================================================================ CORE 0: supervisory loop
static void gpio_setup()
{
    gpio_config_t o = {};
    o.mode = GPIO_MODE_OUTPUT;
    o.pin_bit_mask = (1ULL << PIN_BUZZER) | (1ULL << PIN_LED_GREEN) | (1ULL << PIN_LED_AMBER) | (1ULL << PIN_LED_RED);
    gpio_config(&o);
    gpio_config_t i = {};
    i.mode = GPIO_MODE_INPUT;
    i.pull_up_en = GPIO_PULLUP_ENABLE;
    i.pin_bit_mask = (1ULL << PIN_BTN_SESSION) | (1ULL << PIN_BTN_LEAK);
    gpio_config(&i);
}

static bool button_pressed_edge(int pin, int &low_cnt)
{
    if (gpio_get_level((gpio_num_t)pin) == 0) { ++low_cnt; return low_cnt == 2; }   // ~100 ms debounce, one event per press
    low_cnt = 0;
    return false;
}

static void core0_task(void *)
{
    i2c_init();
    oled_init();
    g_vl_ok = vl_init();
    ESP_LOGI(TAG, "VL53L0X %s, OLED %s", g_vl_ok ? "ok" : "missing", g_oled_ok ? "ok" : "missing");
    adc_cali_init();
    ble_init();

    oled_row(0, "NSQF TRAINER", true);
    oled_row(2, "WARMING UP SENSORS");
    for (int i = 0; i < 8 && g_page_dirty; ++i) oled_flush_step();

    TickType_t last = xTaskGetTickCount();
    uint32_t tick = 0;
    int low_s = 0, low_l = 0;
    uint8_t level = LVL_NORMAL, prev_level = 0xFF;

    for (;;) {
        vTaskDelayUntil(&last, pdMS_TO_TICKS(SENSOR_PERIOD_MS));
        ++tick;
        const uint32_t now = now_ms();

        // --- user input: buttons and BLE control writes
        if (button_pressed_edge(PIN_BTN_SESSION, low_s)) handle_command(g_as.running ? CMD_SESSION_END : CMD_SESSION_START, now);
        if (button_pressed_edge(PIN_BTN_LEAK, low_l))    handle_command(g_as.leak_sim ? CMD_LEAK_END : CMD_LEAK_ONSET, now);
        uint8_t cmd;
        while (xQueueReceive(g_ctrl_q, &cmd, 0) == pdTRUE) handle_command(cmd, now);

        // --- sensors + fusion
        update_features(now, tick);

        // --- acoustic results from Core 1
        AcousticMsg m;
        while (xQueueReceive(g_ac_q, &m, 0) == pdTRUE) handle_acoustic(m);

        // --- standoff compliance: active arc time spent inside 200-350 mm
        bool standoff_ok = (g_f.distance_mm >= STANDOFF_MIN_MM && g_f.distance_mm <= STANDOFF_MAX_MM);
        if (g_as.running && g_arc_active) { ++g_as.arc_ticks; if (standoff_ok) ++g_as.ok_ticks; }

        // --- alert level
        level = LVL_NORMAL;
        if (g_hz_state >= 2) level = LVL_CRITICAL;
        if (g_as.leak_alert) {
            if (g_as.leak_cls == AC_MAJOR_LEAK) level = LVL_CRITICAL;
            else if (level < LVL_WARNING) level = LVL_WARNING;
        }
        if (g_arc_active && !standoff_ok && level < LVL_WARNING) level = LVL_WARNING;

        set_leds(level);
        drive_buzzer(level, tick);

        if (tick % 5 == 0) draw_ui(level, now);          // 4 Hz text refresh
        oled_flush_step();                               // one page per tick
        ble_publish(level, level != prev_level, now);
        prev_level = level;
    }
}

extern "C" void app_main(void)
{
    esp_err_t r = nvs_flash_init();
    if (r == ESP_ERR_NVS_NO_FREE_PAGES || r == ESP_ERR_NVS_NEW_VERSION_FOUND) {
        ESP_ERROR_CHECK(nvs_flash_erase());
        r = nvs_flash_init();
    }
    ESP_ERROR_CHECK(r);
    gpio_setup();

    g_ac_q = xQueueCreate(4, sizeof(AcousticMsg));
    g_ctrl_q = xQueueCreate(8, sizeof(uint8_t));
    configASSERT(g_ac_q && g_ctrl_q);

    xTaskCreatePinnedToCore(core1_audio_task, "audio_c1", 8192, NULL, configMAX_PRIORITIES - 4, NULL, 1);
    xTaskCreatePinnedToCore(core0_task,       "super_c0", 8192, NULL, 5, NULL, 0);
}
