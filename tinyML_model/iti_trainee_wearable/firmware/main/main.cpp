static esp_err_t oled_cmds(const uint8_t *c, size_t n)
{
    uint8_t buf[32];
    if (n > sizeof(buf) - 1) return ESP_ERR_INVALID_SIZE;
    buf[0] = 0x00;
    memcpy(buf + 1, c, n);
    return i2c_wr(ADDR_OLED, buf, n + 1);
}

static void oled_init()
{
    static const uint8_t init[] = {
        0xAE, 0xD5, 0x80, 0xA8, 0x3F, 0xD3, 0x00, 0x40, 0x8D, 0x14, 0x20, 0x00,
        0xA1, 0xC8, 0xDA, 0x12, 0x81, 0xCF, 0xD9, 0xF1, 0xDB, 0x40, 0xA4, 0xA6, 0xAF };
    g_oled_ok = (oled_cmds(init, sizeof(init)) == ESP_OK);
    if (!g_oled_ok) { ESP_LOGW(TAG, "SSD1306 not found at 0x%02X", ADDR_OLED); return; }
    memset(g_fb, 0, sizeof(g_fb));
    memset(g_row_cache, 0, sizeof(g_row_cache));
    g_page_dirty = 0xFF;
}

static void oled_row(int r, const char *s, bool invert = false)
{
    if (r < 0 || r > 7) return;
    char t[OLED_COLS + 1];
    memset(t, ' ', OLED_COLS);
    t[OLED_COLS] = 0;
    for (int i = 0; i < OLED_COLS && s[i]; ++i) {
        int c = toupper((unsigned char)s[i]);
        t[i] = (c >= 32 && c <= 95) ? (char)c : '?';
    }
    if (!strcmp(t, g_row_cache[r]) && invert == g_row_inv[r]) return;
    strcpy(g_row_cache[r], t);
    g_row_inv[r] = invert;
    uint8_t *p = g_fb[r];
    int x = 0;
    for (int i = 0; i < OLED_COLS; ++i) {
        const uint8_t *g = FONT5x7[t[i] - 32];
        for (int k = 0; k < 5; ++k) p[x++] = invert ? (uint8_t)~g[k] : g[k];
        p[x++] = invert ? 0xFF : 0x00;
    }
    while (x < 128) p[x++] = invert ? 0xFF : 0x00;
    g_page_dirty |= (uint8_t)(1u << r);
}

// Sends at most ONE 128-byte page per call (~12 ms at 100 kHz) so the 20 Hz loop never stalls.
static void oled_flush_step()
{
    if (!g_oled_ok || !g_page_dirty) return;
    for (int i = 0; i < 8; ++i) {
        const int pg = (g_flush_next + i) & 7;
        if (g_page_dirty & (1u << pg)) {
            const uint8_t win[] = { 0x21, 0, 127, 0x22, (uint8_t)pg, (uint8_t)pg };
            uint8_t buf[129];
            buf[0] = 0x40;
            memcpy(buf + 1, g_fb[pg], 128);
            if (oled_cmds(win, sizeof(win)) == ESP_OK && i2c_wr(ADDR_OLED, buf, sizeof(buf)) == ESP_OK)
                g_page_dirty &= (uint8_t)~(1u << pg);
            g_flush_next = (uint8_t)((pg + 1) & 7);
            return;
        }
    }
}

// ============================================================================ MLX90614
static uint8_t crc8(const uint8_t *d, size_t n)
{
    uint8_t c = 0;
    for (size_t i = 0; i < n; ++i) {
        c ^= d[i];
        for (int b = 0; b < 8; ++b) c = (c & 0x80) ? (uint8_t)((c << 1) ^ 0x07) : (uint8_t)(c << 1);
    }
    return c;
}

static bool mlx_read(uint8_t reg, float *celsius)
{
    uint8_t rx[3];
    if (i2c_wrrd(ADDR_MLX, &reg, 1, rx, 3) != ESP_OK) return false;
    const uint8_t pec_in[5] = { (uint8_t)(ADDR_MLX << 1), reg, (uint8_t)((ADDR_MLX << 1) | 1), rx[0], rx[1] };
    if (crc8(pec_in, 5) != rx[2]) return false;
    const uint16_t raw = (uint16_t)(rx[0] | (rx[1] << 8));
    if (raw & 0x8000) return false;                     // error flag
    *celsius = raw * 0.02f - 273.15f;
    return true;
}

// ============================================================================ VL53L0X (minimal single-purpose driver, continuous ranging)
static bool vl_w(uint8_t reg, uint8_t v) { const uint8_t b[2] = { reg, v }; return i2c_wr(ADDR_VL53, b, 2) == ESP_OK; }
static uint8_t vl_r(uint8_t reg) { uint8_t v = 0; i2c_wrrd(ADDR_VL53, &reg, 1, &v, 1); return v; }
static uint16_t vl_r16(uint8_t reg) { uint8_t v[2] = {0, 0}; i2c_wrrd(ADDR_VL53, &reg, 1, v, 2); return (uint16_t)((v[0] << 8) | v[1]); }
static bool vl_wmulti(uint8_t reg, const uint8_t *d, uint8_t n)
{ uint8_t b[8]; if (n > 7) return false; b[0] = reg; memcpy(b + 1, d, n); return i2c_wr(ADDR_VL53, b, n + 1) == ESP_OK; }
static bool vl_rmulti(uint8_t reg, uint8_t *d, uint8_t n) { return i2c_wrrd(ADDR_VL53, &reg, 1, d, n) == ESP_OK; }

static uint8_t g_vl_stop_var = 0;
static bool    g_vl_ok = false;

static bool vl_wait_for(uint8_t reg, uint8_t mask, bool want_set, uint32_t timeout_ms)
{
    const uint32_t t0 = now_ms();
    for (;;) {
        const bool set = (vl_r(reg) & mask) != 0;
        if (set == want_set) return true;
        if (now_ms() - t0 > timeout_ms) return false;
        vTaskDelay(1);
    }
}

static bool vl_single_ref_cal(uint8_t vhv_init)
{
    vl_w(0x00, (uint8_t)(0x01 | vhv_init));
    if (!vl_wait_for(0x13, 0x07, true, 500)) return false;
    vl_w(0x0B, 0x01);
    vl_w(0x00, 0x00);
    return true;
}

static bool vl_get_spad_info(uint8_t *count, bool *aperture)
{
    vl_w(0x80, 0x01); vl_w(0xFF, 0x01); vl_w(0x00, 0x00);
    vl_w(0xFF, 0x06); vl_w(0x83, vl_r(0x83) | 0x04);
    vl_w(0xFF, 0x07); vl_w(0x81, 0x01);
    vl_w(0x80, 0x01);
    vl_w(0x94, 0x6B); vl_w(0x83, 0x00);
    const uint32_t t0 = now_ms();
    while (vl_r(0x83) == 0x00) { if (now_ms() - t0 > 500) return false; vTaskDelay(1); }
    vl_w(0x83, 0x01);
    const uint8_t tmp = vl_r(0x92);
    *count = tmp & 0x7F;
    *aperture = (tmp >> 7) & 1;
    vl_w(0x81, 0x00); vl_w(0xFF, 0x06); vl_w(0x83, vl_r(0x83) & ~0x04);
    vl_w(0xFF, 0x01); vl_w(0x00, 0x01);
    vl_w(0xFF, 0x00); vl_w(0x80, 0x00);
    return true;
}

static bool vl_init()
{
    if (vl_r(0xC0) != 0xEE) { ESP_LOGW(TAG, "VL53L0X not found / wrong model id"); return false; }
    vl_w(0x89, vl_r(0x89) | 0x01);            // 2V8 I/O mode
    vl_w(0x88, 0x00);                         // I2C standard mode
    vl_w(0x80, 0x01); vl_w(0xFF, 0x01); vl_w(0x00, 0x00);
    g_vl_stop_var = vl_r(0x91);
    vl_w(0x00, 0x01); vl_w(0xFF, 0x00); vl_w(0x80, 0x00);
    vl_w(0x60, vl_r(0x60) | 0x12);            // disable SIGNAL_RATE_MSRC / PRE_RANGE limit checks
    { const uint8_t lim[2] = { 0x00, 0x20 };  // final-range signal-rate limit 0.25 MCPS (9.7 fixed point = 32)
      vl_wmulti(0x44, lim, 2); }
    vl_w(0x01, 0xFF);

    uint8_t spad_count; bool aperture;
    if (!vl_get_spad_info(&spad_count, &aperture)) return false;
    uint8_t map[6];
    if (!vl_rmulti(0xB0, map, 6)) return false;
    vl_w(0xFF, 0x01); vl_w(0x4F, 0x00); vl_w(0x4E, 0x2C);
    vl_w(0xFF, 0x00); vl_w(0xB6, 0xB4);
    const uint8_t first = aperture ? 12 : 0;
    uint8_t enabled = 0;
    for (uint8_t i = 0; i < 48; ++i) {
        if (i < first || enabled == spad_count) map[i / 8] &= (uint8_t)~(1u << (i % 8));
        else if ((map[i / 8] >> (i % 8)) & 1) ++enabled;
    }
    vl_wmulti(0xB0, map, 6);

    // default tuning settings (ST reference)
    static const uint8_t tune[][2] = {
        {0xFF,0x01},{0x00,0x00},{0xFF,0x00},{0x09,0x00},{0x10,0x00},{0x11,0x00},{0x24,0x01},{0x25,0xFF},
        {0x75,0x00},{0xFF,0x01},{0x4E,0x2C},{0x48,0x00},{0x30,0x20},{0xFF,0x00},{0x30,0x09},{0x54,0x00},
        {0x31,0x04},{0x32,0x03},{0x40,0x83},{0x46,0x25},{0x60,0x00},{0x27,0x00},{0x50,0x06},{0x51,0x00},
        {0x52,0x96},{0x56,0x08},{0x57,0x30},{0x61,0x00},{0x62,0x00},{0x64,0x00},{0x65,0x00},{0x66,0xA0},
        {0xFF,0x01},{0x22,0x32},{0x47,0x14},{0x49,0xFF},{0x4A,0x00},{0xFF,0x00},{0x7A,0x0A},{0x7B,0x00},
        {0x78,0x21},{0xFF,0x01},{0x23,0x34},{0x42,0x00},{0x44,0xFF},{0x45,0x26},{0x46,0x05},{0x40,0x40},
        {0x0E,0x06},{0x20,0x1A},{0x43,0x40},{0xFF,0x00},{0x34,0x03},{0x35,0x44},{0xFF,0x01},{0x31,0x04},
        {0x4B,0x09},{0x4C,0x05},{0x4D,0x04},{0xFF,0x00},{0x44,0x00},{0x45,0x20},{0x47,0x08},{0x48,0x28},
        {0x67,0x00},{0x70,0x04},{0x71,0x01},{0x72,0xFE},{0x76,0x00},{0x77,0x00},{0xFF,0x01},{0x0D,0x01},
        {0xFF,0x00},{0x80,0x01},{0x01,0xF8},{0xFF,0x01},{0x8E,0x01},{0x00,0x01},{0xFF,0x00},{0x80,0x00},
    };
    for (size_t i = 0; i < sizeof(tune) / sizeof(tune[0]); ++i) vl_w(tune[i][0], tune[i][1]);

    vl_w(0x0A, 0x04);                                   // new-sample-ready interrupt (polled)
    vl_w(0x84, vl_r(0x84) & ~0x10);
    vl_w(0x0B, 0x01);
    vl_w(0x01, 0xE8);
    vl_w(0x01, 0x01); if (!vl_single_ref_cal(0x40)) return false;
    vl_w(0x01, 0x02); if (!vl_single_ref_cal(0x00)) return false;
    vl_w(0x01, 0xE8);

    // continuous back-to-back ranging
    vl_w(0x80, 0x01); vl_w(0xFF, 0x01); vl_w(0x00, 0x00);
    vl_w(0x91, g_vl_stop_var);
    vl_w(0x00, 0x01); vl_w(0xFF, 0x00); vl_w(0x80, 0x00);
    vl_w(0x00, 0x02);
    return true;
}

static bool vl_try_read(uint16_t *mm)
{
    if ((vl_r(0x13) & 0x07) == 0) return false;
    *mm = vl_r16(0x14 + 10);
    vl_w(0x0B, 0x01);
    return true;
}

// ============================================================================ sensor fusion state (Core 0)
struct Features {
    float distance_mm = 2000, distance_velocity = 0, temp_object = 25, temp_ambient = 25;
    float delta_temp = 0, uv_index = 0, gas_ppm_slope = 0, gas_ppm = 0;
};
static Features g_f;
static bool g_mlx_ok = false;
static adc_cali_handle_t g_cali = nullptr;
static int g_hz_state = 0;            // debounced hazard state
static uint8_t g_hz_conf = 0;
static bool g_arc_active = false;

static int adc_to_mv(float raw)
{
    int mv = 0;
    if (g_cali && adc_cali_raw_to_voltage(g_cali, (int)(raw + 0.5f), &mv) == ESP_OK) return mv;
    return (int)(raw * 3100.0f / 4095.0f);              // coarse fallback if no calibration data
}

static void adc_cali_init()
{
    adc_cali_line_fitting_config_t c = {};
    c.unit_id = ADC_UNIT_1;
    c.atten = ADC_ATTEN_DB_12;
    c.bitwidth = ADC_BITWIDTH_12;
    if (adc_cali_create_scheme_line_fitting(&c, &g_cali) != ESP_OK) g_cali = nullptr;
}

static void take_slow_adc(float *mq_raw, float *uv_raw)
{
    uint32_t s0, c0, s1, c1;
    portENTER_CRITICAL(&g_slow_mux);
    s0 = g_slow.sum[0]; c0 = g_slow.cnt[0]; s1 = g_slow.sum[1]; c1 = g_slow.cnt[1];
    g_slow.sum[0] = g_slow.cnt[0] = g_slow.sum[1] = g_slow.cnt[1] = 0;
    portEXIT_CRITICAL(&g_slow_mux);
    if (c0) *mq_raw = (float)s0 / c0;                   // otherwise keep previous value
    if (c1) *uv_raw = (float)s1 / c1;
}

static float mq2_rs_kohm(float mv_pin)
{
    float vout = mv_pin * 0.001f * MQ2_DIVIDER;
    if (vout < 0.01f) vout = 0.01f;
    if (vout > MQ2_VCC - 0.01f) vout = MQ2_VCC - 0.01f;
    return MQ2_RL_KOHM * (MQ2_VCC - vout) / vout;
}

static void update_features(uint32_t now, uint32_t tick)
{
    static float mq_raw = 0, uv_raw = 0;
    static uint16_t last_mm = 2000;
    static int mlx_fail = 0, vl_fail = 0;
    static float prev_dist = 2000, vel_ema = 0;
    static float ppm_ema = 0, ppm_hist[20] = {0};
    static int ppm_head = 0;
    static float r0 = 0, cal_sum = 0; static int cal_n = 0;
    static bool gas_ready = false;

    take_slow_adc(&mq_raw, &uv_raw);

    // --- temperatures
    float t;
    if (mlx_read(0x07, &t)) { g_f.temp_object = t; mlx_fail = 0; g_mlx_ok = true; } else if (++mlx_fail > 20) g_mlx_ok = false;
    if (mlx_read(0x06, &t)) g_f.temp_ambient = t;
    if (!g_mlx_ok) { g_f.temp_object = g_f.temp_ambient; }
    g_f.delta_temp = g_f.temp_object - g_f.temp_ambient;

    // --- distance
    uint16_t mm;
    if (g_vl_ok) {
        if (vl_try_read(&mm)) { last_mm = mm; vl_fail = 0; } else if (++vl_fail > 40) last_mm = 2000;
    }
    float d = (!g_vl_ok || last_mm >= 2000) ? 2000.0f : (float)last_mm;     // 8190 etc. = out of range
    if (d < 20.0f) d = 20.0f;
    g_f.distance_mm = d;
    const float vel = (d - prev_dist) / (SENSOR_PERIOD_MS * 0.001f);
    prev_dist = d;
    vel_ema += 0.3f * (vel - vel_ema);
    g_f.distance_velocity = vel_ema;

    // --- UV index (GUVA-S12SD: ~0.1 V per index)
    float uvi = adc_to_mv(uv_raw) / 100.0f;
    g_f.uv_index = uvi < 0 ? 0 : (uvi > 12 ? 12 : uvi);

    // --- gas (MQ-2 LPG curve), slope over a 1 s window
    const float rs = mq2_rs_kohm((float)adc_to_mv(mq_raw));
    const uint32_t s_since_boot = now / 1000;
    if (!gas_ready) {
        if (s_since_boot >= (uint32_t)(MQ2_WARMUP_S - MQ2_CAL_WINDOW_S)) { cal_sum += rs; ++cal_n; }
        if (s_since_boot >= (uint32_t)MQ2_WARMUP_S && cal_n > 0) {
            r0 = (cal_sum / cal_n) / MQ2_CLEAN_RATIO;
            ppm_ema = 574.25f * powf((cal_sum / cal_n) / r0, -2.222f);
            for (int i = 0; i < 20; ++i) ppm_hist[i] = ppm_ema;
            gas_ready = true;
            ESP_LOGI(TAG, "MQ-2 calibrated: R0 = %.2f kOhm", r0);
        }
        g_f.gas_ppm_slope = 0; g_f.gas_ppm = 0;
    } else {
        const float ppm = 574.25f * powf(rs / r0, -2.222f);
        ppm_ema += 0.15f * (ppm - ppm_ema);
        const float old = ppm_hist[ppm_head];
        ppm_hist[ppm_head] = ppm_ema;
        ppm_head = (ppm_head + 1) % 20;
        g_f.gas_ppm = ppm_ema;
        g_f.gas_ppm_slope = (ppm_ema - old) / 1.0f;      // ppm per second (20 ticks)
    }

    // --- arc detection with hysteresis (used for the standoff metric too)
    static int on_cnt = 0, off_cnt = 0;
    if (g_f.uv_index >= UV_ARC_ON) { ++on_cnt; off_cnt = 0; } else if (g_f.uv_index < UV_ARC_OFF) { ++off_cnt; on_cnt = 0; }
    if (!g_arc_active && on_cnt >= 3) g_arc_active = true;
    if (g_arc_active && off_cnt >= 10) g_arc_active = false;

    // --- hazard forest + hard interlock floors
    const float x[HZ_FEATURE_COUNT] = { g_f.distance_mm, g_f.distance_velocity, g_f.temp_object,
                                        g_f.temp_ambient, g_f.delta_temp, g_f.uv_index,
                                        gas_ready ? g_f.gas_ppm_slope : 0.0f };
    uint8_t conf = 0;
    int s = hazard_predict(x, &conf);
    if (!gas_ready && s == 3) s = 0;
    int floor_s = 0;
    if (g_f.distance_mm < PROX_BREACH_MM) floor_s = 2;
    else if (gas_ready && g_f.gas_ppm_slope > GAS_SLOPE_HARD) floor_s = 3;
    else if (g_f.temp_object > OVERHEAT_HARD_C) floor_s = 4;
    if (floor_s && (s == 0 || s == 1)) s = floor_s;

    static int cand = 0, cand_n = 0;                    // debounce: 2 ticks to enter, 5 to return to normal
    if (s == cand) ++cand_n; else { cand = s; cand_n = 1; }
    const int need = (cand == 0) ? 5 : 2;
    if (cand != g_hz_state && cand_n >= need) { g_hz_state = cand; g_hz_conf = conf; }
    (void)tick;
}

// ============================================================================ NSQF assessment
struct Assessment {
    bool     running = false, complete = false;
    uint32_t start_ms = 0, end_ms = 0;
    bool     leak_sim = false, onset_marked = false;
    uint32_t onset_ms = 0;
    int32_t  reaction_ms = -1;
    uint16_t false_alarms = 0;
    uint32_t arc_ticks = 0, ok_ticks = 0;
    // detector state
    int      hits = 0, misses = 0;
    bool     leak_alert = false;
    uint8_t  leak_cls = 0;
    // outputs
    uint8_t  score = 0;
};
static Assessment g_as;
static AcousticMsg g_last_ac = { 0, 0, 0 };
static bool g_have_ac = false;

static void assess_reset_session()
{
    const bool keep_alert = g_as.leak_alert;
    const uint8_t keep_cls = g_as.leak_cls;
    g_as = Assessment();
    g_as.leak_alert = keep_alert; g_as.leak_cls = keep_cls;
}

static float standoff_pct(bool *valid)
{
    *valid = (g_as.arc_ticks * SENSOR_PERIOD_MS) >= (uint32_t)(MIN_ARC_S_SCORED * 1000);
    return g_as.arc_ticks ? 100.0f * g_as.ok_ticks / g_as.arc_ticks : 0.0f;
}

static uint8_t compute_score()
{
    float w = 0, acc = 0;
    if (g_as.onset_marked) {                             // reaction component (weight 0.4)
        float s = 0;
        if (g_as.reaction_ms >= 0) {
            const float rt = g_as.reaction_ms / 1000.0f;
            s = rt <= RT_FULL_MARK_S ? 100.0f
              : (rt >= RT_ZERO_MARK_S ? 0.0f : 100.0f * (RT_ZERO_MARK_S - rt) / (RT_ZERO_MARK_S - RT_FULL_MARK_S));
        }
        acc += 0.4f * s; w += 0.4f;
    }
    { float fa = 100.0f - FA_PENALTY * g_as.false_alarms; if (fa < 0) fa = 0; acc += 0.2f * fa; w += 0.2f; }
    bool v; const float sp = standoff_pct(&v);
    if (v) { acc += 0.4f * sp; w += 0.4f; }
    return (uint8_t)(acc / w + 0.5f);
}

static void session_start(uint32_t now)
{
    assess_reset_session();
    g_as.running = true; g_as.start_ms = now;
    ESP_LOGI(TAG, "session started");
}

static void session_end(uint32_t now)
{
    if (!g_as.running) return;
    g_as.running = false; g_as.complete = true; g_as.end_ms = now;
    g_as.leak_sim = false;
    g_as.score = compute_score();
    bool v; const float sp = standoff_pct(&v);
    ESP_LOGI(TAG, "session end: RT=%ld ms FA=%u standoff=%.0f%%%s score=%u",
             (long)g_as.reaction_ms, g_as.false_alarms, sp, v ? "" : "(n/a)", g_as.score);
}

static void handle_command(uint8_t cmd, uint32_t now)
{
    switch (cmd) {
    case CMD_SESSION_START: session_start(now); break;
    case CMD_SESSION_END:   session_end(now); break;
    case CMD_RESET:         assess_reset_session(); break;
    case CMD_LEAK_ONSET:
        if (g_as.running && !g_as.leak_sim) {
            g_as.leak_sim = true;
            if (!g_as.onset_marked) { g_as.onset_marked = true; g_as.onset_ms = now; g_as.reaction_ms = -1; }
            // if an alert is already latched when the drill starts, it must clear and re-trigger
            // to count as a detection of THIS leak
        }
        break;
    case CMD_LEAK_END: g_as.leak_sim = false; break;
    }
}

static void handle_acoustic(const AcousticMsg &m)
{
    g_last_ac = m; g_have_ac = true;
    const bool leak_now = (m.cls == AC_MINOR_LEAK || m.cls == AC_MAJOR_LEAK) && m.conf_pct >= (uint8_t)(LEAK_CONF_MIN * 100);
    if (leak_now) { ++g_as.hits; g_as.misses = 0; g_as.leak_cls = m.cls; }
    else          { ++g_as.misses; g_as.hits = 0; }
    if (!g_as.leak_alert && g_as.hits >= LEAK_CONFIRM_WIN) {
        g_as.leak_alert = true;                         // rising edge
        if (g_as.running) {
            if (g_as.leak_sim) {
                if (g_as.reaction_ms < 0 && g_as.onset_marked) g_as.reaction_ms = (int32_t)(m.ts_ms - g_as.onset_ms);
            } else {
                ++g_as.false_alarms;                    // alert while no leak is being simulated
            }
        }
    } else if (g_as.leak_alert && g_as.misses >= LEAK_CLEAR_WIN) {
        g_as.leak_alert = false;
    }
}

